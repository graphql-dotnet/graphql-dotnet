#!/usr/bin/env python3
"""Generate pinned, benchmark-only historical rules; no production sources change."""

import argparse
import hashlib
from pathlib import Path
import re
import subprocess
import urllib.request


HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[2]
RULE = "src/GraphQL/Validation/Rules/OverlappingFieldsCanBeMerged.cs"
SNAPSHOTS = [
    ("Original", "b3c64151d70e977752c8526c00f13bf2530399f6",
     "213c910bfc523ab0ec951053b882f63724999f99b00d63871f92db6832c20998"),
    ("PR4426", "60fe08bd5007a239ce420c0d049c3e562591b7a3",
     "42d9d4c781ec1105752434ff97c28ecb8fe8f7fae2526d55e9b395e1a4ba5a00"),
]


def read_snapshot(name, revision, local):
    if local:
        return Path(local).read_text()
    result = subprocess.run(["git", "show", f"{revision}:{RULE}"], cwd=ROOT,
                            capture_output=True, text=True)
    if result.returncode == 0:
        return result.stdout
    url = f"https://raw.githubusercontent.com/graphql-dotnet/graphql-dotnet/{revision}/{RULE}"
    with urllib.request.urlopen(url) as response:
        return response.read().decode("utf-8")


def adapt(source, name):
    # Keep algorithm bodies verbatim. Share the unchanged public diagnostic DTOs
    # so historical rules can construct the production validation error type.
    for dto in ("Conflict", "ConflictReason", "Message"):
        start = source.index(f"    public class {dto}\n")
        start = source.rfind("    /// <summary>", 0, start)
        brace = source.index("{", start)
        depth = 1
        end = brace + 1
        while depth:
            depth += (source[end] == "{") - (source[end] == "}")
            end += 1
        source = source[:start] + source[end:]
    source = re.sub(r"\bOverlappingFieldsCanBeMerged\b", f"{name}OverlappingFields", source)
    source = source.replace("namespace GraphQL.Validation.Rules;",
                            "namespace GraphQL.Benchmarks.Historical;")
    if name != "Original":
        source = source[:source.index("internal static class ISelectionNodeExtensions")]
    return ("// <auto-generated/>\n#nullable enable\n"
            "using GraphQL.Validation;\nusing GraphQL.Validation.Rules;\n"
            "using static GraphQL.Validation.Rules.OverlappingFieldsCanBeMerged;\n" + source)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--original", help="Optional local original rule snapshot")
    parser.add_argument("--pr4426", help="Optional local PR 4426 rule snapshot")
    args = parser.parse_args()
    output = HERE.parent / "obj" / "OverlappingFieldsComparison"
    output.mkdir(parents=True, exist_ok=True)
    for name, revision, digest in SNAPSHOTS:
        source = read_snapshot(name, revision, getattr(args, name.lower())).rstrip() + "\n"
        actual = hashlib.sha256(source.encode()).hexdigest()
        if actual != digest:
            raise ValueError(f"{name} snapshot SHA-256 mismatch: {actual}")
        (output / f"{name}OverlappingFields.cs").write_text(adapt(source, name))
        print(f"Prepared {name} from {revision}")

    # Experimental control: group every multi-field selection instead of first
    # scanning for unaliased, argument-free leaves. Everything else is identical.
    source = (ROOT / RULE).read_text()
    (output / "SinglePassOverlappingFields.cs").write_text(adapt(source, "SinglePass"))
    fast = (ROOT / RULE.replace(".cs", ".FastValidation.cs")).read_text()
    start = fast.index("        private static bool IsTrivial(")
    end = fast.index("        private bool Check(", start)
    fast = fast[:start] + """        private static bool IsTrivial(GraphQLSelectionSet selectionSet)
            => selectionSet.Selections.Count == 1 && selectionSet.Selections[0] is GraphQLField;

""" + fast[end:]
    fast = fast.replace("OverlappingFieldsCanBeMerged", "SinglePassOverlappingFields")
    fast = fast.replace("SinglePassOverlappingFieldsError", "OverlappingFieldsCanBeMergedError")
    fast = fast.replace("namespace GraphQL.Validation.Rules;", "namespace GraphQL.Benchmarks.Historical;")
    fast = "// <auto-generated/>\n#nullable enable\nusing GraphQL.Validation;\nusing GraphQL.Validation.Rules;\n" + fast
    (output / "SinglePassOverlappingFields.FastValidation.cs").write_text(fast)
    print("Prepared single-pass control from current working tree")


if __name__ == "__main__":
    main()
